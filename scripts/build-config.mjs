// Writes public/config.js from environment variables so no key is ever committed.
// Vercel runs this on every deploy (see vercel.json). Locally, an existing public/config.js is left alone.
import { existsSync, writeFileSync } from 'node:fs';

const out = new URL('../public/config.js', import.meta.url);
const env = (name) => (process.env[name] || '').trim();
const onVercel = Boolean(process.env.VERCEL);

function fail(message) {
  console.error('\nconfig error: ' + message + '\n');
  process.exit(1);
}

const url = env('SUPABASE_URL');
const key = env('SUPABASE_ANON_KEY');

if (!url && !key) {
  if (!onVercel && existsSync(out)) {
    console.log('config: no env vars set, keeping the existing public/config.js');
    process.exit(0);
  }
  fail('Set SUPABASE_URL and SUPABASE_ANON_KEY in the Vercel project settings (Settings > Environment Variables).');
}

if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) {
  fail('SUPABASE_URL must look like https://your-project-ref.supabase.co (no trailing slash, no path).');
}
if (!key) fail('SUPABASE_ANON_KEY is empty.');

// The browser key must be the publishable/anon key. A service-role or secret key here would give everyone full database access.
if (key.startsWith('sb_secret_')) fail('SUPABASE_ANON_KEY is a SECRET key. Use the publishable (anon) key instead.');
if (key.split('.').length === 3) {
  try {
    const claims = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString('utf8'));
    if (claims.role === 'service_role') fail('SUPABASE_ANON_KEY is a service_role key. Use the anon/publishable key instead.');
  } catch {
    fail('SUPABASE_ANON_KEY is not a valid key.');
  }
} else if (!key.startsWith('sb_publishable_')) {
  fail('SUPABASE_ANON_KEY is not recognised. Expected a key starting with sb_publishable_ (or the legacy anon JWT).');
}

const contact = env('CONTACT_EMAIL');
if (contact && !/^[^\s@<>"']+@[^\s@<>"']+\.[^\s@<>"']+$/.test(contact)) fail('CONTACT_EMAIL is not a valid email address.');

const payments = env('PAYMENTS_ENABLED') === 'true';
if (payments) console.warn('config: PAYMENTS_ENABLED=true. Only do this after docs/PAYMENTS.md is complete.');

const lines = [
  '// Generated by scripts/build-config.mjs. Do not edit; change the environment variables instead.',
  `window.DROPLIVE_SUPABASE_URL = ${JSON.stringify(url)};`,
  `window.DROPLIVE_SUPABASE_ANON_KEY = ${JSON.stringify(key)};`,
  `window.DROPLIVE_PAYMENTS_ENABLED = ${payments};`,
  `window.DROPLIVE_CONTACT_EMAIL = ${JSON.stringify(contact)};`,
  ''
];
writeFileSync(out, lines.join('\n'));
console.log('config: wrote public/config.js for ' + url);
